@pytest.mark.parametrize("seed, xprv, xpub", VECTORS_MASTER)
def test_official_master_keys_from_seed(seed, xprv, xpub):
    key = master_from_seed(bytes.fromhex(seed))
    assert encode_extended_key(key) == xprv
    decoded = decode_extended_key(xprv)
    assert decoded == key
    pub = decode_extended_key(xpub)
    assert pub.private is False
    assert pub.chain_code == key.chain_code
    assert pub.depth == 0
    assert pub.fingerprint == b"\x00\x00\x00\x00"
    assert pub.child == 0
    assert pub.network == "mainnet"


@pytest.mark.parametrize("encoded", ALL_VALID_KEYS)
def test_official_keys_roundtrip(encoded):
    key = decode_extended_key(encoded)
    assert encode_extended_key(key) == encoded
    assert key.prefix == encoded[:4]
    if key.depth == 0:
        assert key.fingerprint == b"\x00\x00\x00\x00"
        assert key.child == 0
        assert not key.hardened


@pytest.mark.parametrize("encoded", INVALID_KEYS)
def test_official_invalid_keys_are_rejected(encoded):
    with pytest.raises(ValueError):
        decode_extended_key(encoded)


@pytest.mark.parametrize("entropy, mnemonic, seed, xprv", BIP39_VECTORS)
def test_official_bip39_xprv_from_seed(entropy, mnemonic, seed, xprv):
    key = master_from_seed(bytes.fromhex(seed))
    assert encode_extended_key(key) == xprv
    # The same seed comes from the mnemonic with the published passphrase.
    assert mnemonic_to_seed(mnemonic, "TREZOR") == bytes.fromhex(seed)


def test_vector1_child_fields():
    # Chain m/0H: depth 1, hardened index 0, non-zero parent fingerprint.
    prv = decode_extended_key(
        "xprv9uHRZZhk6KAJC1avXpDAp4MDc3sQKNxDiPvvkX8Br5ngLNv1TxvUxt4cV1rGL5hj6KCesnDYUhd7oWgT11eZG7XnxHrnYeSvkzY7d2bhkJ7"
    )
    assert prv.depth == 1
    assert prv.hardened
    assert prv.child == HARDENED
    assert prv.child_index == 0
    assert prv.fingerprint != b"\x00\x00\x00\x00"
    assert len(prv.fingerprint) == 4
    assert len(prv.chain_code) == 32
    assert len(prv.key) == 32


def test_testnet_version_roundtrip():
    main = decode_extended_key(VECTORS_MASTER[0][1])
    testnet = main._replace(network="testnet")
    encoded = encode_extended_key(testnet)
    assert encoded.startswith("tprv")
    decoded = decode_extended_key(encoded)
    assert decoded.network == "testnet"
    assert decoded.private is True
    assert decoded.key == main.key
    assert decoded.chain_code == main.chain_code
    pub = decode_extended_key(VECTORS_MASTER[0][2])._replace(network="testnet")
    assert encode_extended_key(pub).startswith("tpub")
    assert decode_extended_key(encode_extended_key(pub)).key == pub.key


